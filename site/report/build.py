"""Build the on-site report page from docs/REPORT.md.

docs/REPORT.md stays the only copy of the text; run this after editing it:

    python site/report/build.py
"""
import re
from pathlib import Path

import markdown

from charts import FIGURES

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
REPO = "https://github.com/vidit-16/kant-fix-it"
SRC = ROOT / "docs" / "REPORT.md"


text = SRC.read_text(encoding="utf-8")
md = markdown.Markdown(extensions=["tables", "fenced_code", "toc", "sane_lists"],
                       extension_configs={"toc": {"toc_depth": "2-3"}})
body = md.convert(text)
toc = md.toc

# the title becomes the page header
m = re.match(r'\s*<h1 id="[^"]*">(.*?)</h1>', body, flags=re.S)
title = m.group(1)
body = body[m.end():]
toc = re.sub(r'^\s*<div class="toc">\s*|\s*</div>\s*$', "", toc)
toc = re.sub(r'<li><a href="#[^"]*">' + re.escape(title) + r'</a>\s*<ul>(.*)</ul>\s*</li>', r"\1", toc, flags=re.S)


# figures: redrawn in the site's style from the stored result files (charts.py)
def figure(mo):
    return FIGURES[mo.group(1)]()


body = re.sub(r'<p><img alt="([^"]*)" src="([^"]+)" ?/?></p>', figure, body)

# links to other project documents go to GitHub
body = re.sub(r'href="(?!https?:|#)([^"]+)"', lambda mo: f'href="{REPO}/blob/main/docs/{mo.group(1)}"', body)

# wide tables scroll sideways on phones instead of breaking the page
body = body.replace("<table>", '<div class="tablewrap"><table>').replace("</table>", "</table></div>")

page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Report: acceptance gates versus prices</title>
<meta name="description" content="{title}. Full report by Vidit Choudhary.">
<link rel="icon" href="../favicon.svg" type="image/svg+xml">
<meta property="og:title" content="Acceptance gates versus prices: full report">
<meta property="og:description" content="Five pre-registered studies of whether a conscience or a price keeps self-improving agents from wrecking a shared system.">
<meta property="og:image" content="https://kant-fix-it-web.vercel.app/og.png">
<meta name="twitter:card" content="summary_large_image">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400;12..96,500;12..96,600;12..96,700;12..96,800&display=swap" rel="stylesheet">
<link rel="stylesheet" href="report.css">
</head>
<body>
<!-- generated by site/report/build.py from docs/REPORT.md; edit that file, not this one -->
<header class="bar">
  <a class="home" href="../">Kant fix it</a>
  <div class="tools">
    <button type="button" id="print">Save as PDF</button>
    <a href="{REPO}/blob/main/docs/REPORT.md">Source</a>
  </div>
</header>
<div class="layout">
  <nav class="toc" aria-label="Contents"><b>Contents</b>{toc}</nav>
  <article class="report">
    <p class="kicker">Full report</p>
    <h1>{title}</h1>
    <p class="by">Vidit Choudhary</p>
    <details class="toc-mini"><summary>Contents</summary>{toc}</details>
{body}
  </article>
</div>
<footer class="end">
  <a href="../">Back to the game</a>
  <span>&copy; 2026 <a href="https://www.linkedin.com/in/vidit-choudhary">Vidit Choudhary</a> &middot; MIT licence</span>
</footer>
<script>document.getElementById("print").addEventListener("click", () => print());</script>
<script src="toc.js"></script>
</body>
</html>
"""
(HERE / "index.html").write_text(page, encoding="utf-8")
print("wrote", HERE / "index.html")
